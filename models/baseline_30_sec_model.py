from functions import *


# BASELINE MODEL WITH 57_FEATURES_30_SEC MODEL
# References: Kaavya Mahajan, "Training a TensorFlow model 
# for predicting the Genres of Popular Songs"

"""

Training the Model Using GTZAN 57 Features (30-Second Segments)

Pipeline:

1. Load and Prepare Data: Load the CSV file generated by the
preprocessing pipeline.

2. Split Data: Separate the dataset into features (X) and labels (y).

3. Scale Features: Standardize the feature values to improve model training.

4. Encode Labels: Convert string labels into numerical values.

5. Build and Train the Model: Build the neural network and
train it using the prepared data.

6. Evaluate the Model: Run diagnostics to assess model performance
and identify areas for improvement.

------------------------------------------------------------------

Training and Validation Performance Analysis of the Model:

GTZAN RAW FEATURES:
Dataset: features_30_sec.csv

* Test Accuracy: 70.50% - 74.50%
* Test Loss: 1.0275 - 1.0674 

"""


# ==================== LOAD AND PREPARE DATA ====================
df = pd.read_csv(
    "Data/" \
    "features_30_sec.csv"
    )

x = df.drop(columns=["filename", "label", "length"])
y = df["label"]

# Separate test set
x_train_full, x_test, y_train_full, y_test = split_data(
    x, y,
    test_size=0.2,
    random_state=42,
)

# Split again for validation sets
x_train, x_val, y_train, y_val = split_data(
    x_train_full,
    y_train_full,
    test_size=0.2,
    random_state=42
)

# ================== SCALE FEATURES/ ENCODE LABELS ===============

x_train_scaled, x_val_scaled, x_test_scaled, scaler = (
    scale_features(x_train, x_val, x_test)
)

label_encoder = LabelEncoder()

y_train_encoded = label_encoder.fit_transform(y_train)
y_val_encoded = label_encoder.fit_transform(y_val)
y_test_encoded = label_encoder.transform(y_test)


# ===================== NEURAL NETWORK ===========================
# Build Model
# Input: 57 Audio Features
# 64 Neurons, ReLU: Rectified Linear Unit
# softmax: Converts scores into probabilities totaling 1

model = build_model(
    shape=x_train_scaled.shape[1],
    dense_1=64,
    dense_2=64,
    num_classes=len(label_encoder.classes_)
)


# Train Model
# epochs=30: Passes through training data up to 30 times
# batch_size=32: Processes 32 training examples per batch
# validation_split=0.2: Reserves 20% of training data for validation

history = model.fit(
    x_train_scaled,
    y_train_encoded,
    epochs=100,
    batch_size=32,
    validation_data=(x_val_scaled, y_val_encoded),
    callbacks=callbacks(),
    class_weight=get_class_weights(y_train_encoded),
    verbose=1
)

# ====================== EVALUATE MODEL ===========================
results = evaluate_model(
    model,
    x_test_scaled,
    y_test_encoded,
    label_encoder,
    title="GTZAN 30-Second Model",
    plot=True
)

